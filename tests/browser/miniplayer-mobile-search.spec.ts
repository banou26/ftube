const installHomeAndShortsOverlay = (thumbUrl: string) => {
  if (window.top !== window) return
  const post = Object.getOwnPropertyDescriptor(MessagePort.prototype, 'postMessage')!.value as (
    this: MessagePort,
    message: unknown,
    ...rest: unknown[]
  ) => void

  const homeItems = [
    {
      kind: 'video',
      id: 'dockvid0001',
      title: 'Home Feed Video',
      inlinePlayerParams: 'params-dockvid0001',
      description: 'Home video description',
      descriptionSnippet: 'Home video snippet',
      snippetRuns: [{ text: 'Home video snippet', bold: false }],
      thumbnail: thumbUrl,
      thumbnailSrcset: undefined,
      animatedThumbnail: undefined,
      durationSeconds: 180,
      isMusic: false,
      viewCount: '120K',
      publishedText: '2d ago',
      isLive: false,
      isUpcoming: false,
      isShort: false,
      progressPercent: undefined,
      badges: [],
      channel: { id: 'UCdock', name: 'Channel One', avatar: thumbUrl, isVerified: true, isVerifiedArtist: false },
      chapters: [],
      chaptersTitle: undefined,
      byline: [],
      collaborators: [],
    },
  ]

  MessagePort.prototype.postMessage = function (this: MessagePort, message: unknown, ...rest: unknown[]) {
    const req = message as { id?: number, method?: string, args?: unknown[] } | null
    if (!req?.method) return post.call(this, message, ...rest)
    const reply = (result: unknown) => {
      setTimeout(() => this.dispatchEvent(new MessageEvent('message', { data: { id: req.id, result } })), 0)
    }
    if (req.method === 'home') {
      reply({ items: homeItems, shorts: [], chips: [], cursor: undefined })
      return
    }
    if (req.method === 'shorts') {
      const seed = typeof req.args?.[0] === 'string' ? req.args[0] : undefined
      const all = [
        { id: 'shortvid001', poster: thumbUrl, title: 'Vertical Short One' },
        { id: 'shortvid002', poster: thumbUrl, title: 'Vertical Short Two' },
      ]
      const ordered = seed && all.some(item => item.id === seed)
        ? [all.find(item => item.id === seed)!, ...all.filter(item => item.id !== seed)]
        : all
      reply({ items: ordered, cursor: null })
      return
    }
    if (req.method === 'searchSuggestions') {
      reply([])
      return
    }
    return post.call(this, message, ...rest)
  } as typeof MessagePort.prototype.postMessage
}

const dock = (page: Page) => page.locator('aside[aria-label="Miniplayer"]')

const box = (locator: Locator) => locator.evaluate((element) => {
  const { left, top, right, bottom, width, height } = element.getBoundingClientRect()
  return { left, top, right, bottom, width, height }
})

const horizontalOverflow = (page: Page) => page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)

test('collapses mobile Watch and Shorts miniplayers into a compact strip when Search opens', async ({ page }) => {
  test.setTimeout(120_000)
  const pageErrors: string[] = []
  page.on('pageerror', error => pageErrors.push(error.message))

  await hideFknNotice(page)
  await installMockPlayback(page)
  await page.route('**/src/player/shaka.ts*', route =>
    route.fulfill({ status: 200, contentType: 'application/javascript', body: SHAKA_FULL_MOCK_JS }),
  )
  await page.addInitScript(installHomeAndShortsOverlay, THUMB)
  await page.setViewportSize({ width: 390, height: 844 })

  // Start playing a regular Watch video, then leave to Home so the Watch miniplayer docks at mobile width.
  await page.goto('/watch?v=dockvid0001')
  const watchVideo = page.locator('[data-player-root] video')
  await expect(watchVideo).toBeVisible({ timeout: 30_000 })
  await page.getByRole('link', { name: 'FTube home', exact: true }).click()
  await expect(page).toHaveURL(/\/$/)

  const mini = dock(page)
  await expect(mini).toBeVisible({ timeout: 30_000 })
  await expect(mini).not.toHaveAttribute('data-collapsed', 'true')
  const expandedBox = await box(mini)
  expect(expandedBox.height).toBeGreaterThan(200)

  // Opening mobile Search collapses the miniplayer into a compact strip clear of the query input.
  await page.locator('header button.open-search').click()
  await expect(page.locator('header')).toHaveClass(/search-open/)
  await expect(mini).toHaveAttribute('data-collapsed', 'true')

  const compactBox = await box(mini)
  expect(compactBox.height).toBeLessThanOrEqual(64)
  expect(compactBox.bottom).toBeLessThanOrEqual(844)
  expect(await horizontalOverflow(page)).toBe(0)

  const searchInput = page.locator('header input[name="search_query"]')
  await expect(searchInput).toBeFocused()
  const inputBox = await box(searchInput)
  expect(inputBox.bottom).toBeLessThan(compactBox.top)

  // Compact Play / Pause toggles playback state while keeping Search open.
  const miniVideo = mini.locator('video')
  await expect.poll(() => miniVideo.evaluate(el => (el as HTMLVideoElement).paused)).toBe(false)
  await mini.getByRole('button', { name: 'Pause', exact: true }).click()
  await expect.poll(() => miniVideo.evaluate(el => (el as HTMLVideoElement).paused)).toBe(true)
  await mini.getByRole('button', { name: 'Play', exact: true }).click()
  await expect.poll(() => miniVideo.evaluate(el => (el as HTMLVideoElement).paused)).toBe(false)
  await expect(page.locator('header')).toHaveClass(/search-open/)

  // Closing mobile Search restores the full miniplayer.
  await page.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(page.locator('header')).not.toHaveClass(/search-open/)
  await expect(mini).not.toHaveAttribute('data-collapsed', 'true')
  expect((await box(mini)).height).toBeGreaterThan(200)

  // Opening Search again, typing a query, and submitting keeps the compact strip usable over /results.
  await page.locator('header button.open-search').click()
  await expect(mini).toHaveAttribute('data-collapsed', 'true')
  await searchInput.fill('search query test')
  await searchInput.press('Enter')
  await expect(page).toHaveURL(/\/results\?search_query=search\+query\+test|\/results\?search_query=search%20query%20test/)
  await expect(page.getByRole('link', { name: 'First Search Video' })).toBeVisible({ timeout: 20_000 })
  await expect(mini).toHaveAttribute('data-collapsed', 'true')
  expect(await horizontalOverflow(page)).toBe(0)

  // Expanding returns to /watch, closes mobile Search, and un-docks the player.
  await mini.getByRole('button', { name: 'Expand', exact: true }).click()
  await expect(page).toHaveURL(/\/watch\?v=dockvid0001/)
  await expect(page.locator('header')).not.toHaveClass(/search-open/)
  await expect(mini).toHaveAttribute('aria-hidden', 'true')

  // Re-dock on Home, open Search, and Close miniplayer stops playback.
  await page.getByRole('link', { name: 'FTube home', exact: true }).click()
  await expect(mini).toBeVisible({ timeout: 20_000 })
  await page.locator('header button.open-search').click()
  await expect(mini).toHaveAttribute('data-collapsed', 'true')
  await mini.getByRole('button', { name: 'Close miniplayer', exact: true }).click()
  await expect(mini).toHaveAttribute('aria-hidden', 'true')

  // A vertical Short miniplayer also collapses on mobile Search and expands back to /shorts/<id>.
  await page.goto('/shorts/shortvid001')
  const activeSlide = page.locator('[data-short-id="shortvid001"][data-active="true"]')
  await expect(activeSlide.locator('video')).toBeVisible({ timeout: 30_000 })
  await expect.poll(
    () => activeSlide.locator('video').evaluate(el => (el as HTMLVideoElement).currentTime),
    { timeout: 20_000 },
  ).toBeGreaterThan(0.5)

  await page.getByRole('link', { name: 'FTube home', exact: true }).click()
  await expect(page).toHaveURL(/\/$/)
  await expect(mini).toBeVisible({ timeout: 20_000 })
  await expect(mini).toHaveAttribute('data-miniplayer-aspect', 'vertical')

  await page.locator('header button.open-search').click()
  await expect(mini).toHaveAttribute('data-collapsed', 'true')
  const shortCompactBox = await box(mini)
  expect(shortCompactBox.height).toBeLessThanOrEqual(64)
  expect(await horizontalOverflow(page)).toBe(0)

  await mini.getByRole('button', { name: 'Expand', exact: true }).click()
  await expect(page).toHaveURL(/\/shorts\/shortvid001/)
  await expect(page.locator('header')).not.toHaveClass(/search-open/)
  await expect(mini).toHaveAttribute('aria-hidden', 'true')

  expect(pageErrors).toEqual([])
})
