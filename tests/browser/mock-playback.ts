/**
 * Installs deterministic local engine answers and an offline Shaka playback controller
 * so player, miniplayer, and HoverPreview flows run quickly without external YouTube requests.
 */
export const installMockPlayback = async (page: Page) => {
  await page.route('**/src/player/shaka.ts*', route =>
    route.fulfill({ status: 200, contentType: 'application/javascript', body: SHAKA_MOCK_JS }))
  await page.route('https://returnyoutubedislikeapi.com/**', route =>
    route.fulfill({ headers: { 'access-control-allow-origin': '*' }, json: { likes: 0, dislikes: 0 } }))
  await page.route('https://sponsor.ajay.app/**', route =>
    route.fulfill({ status: 404, headers: { 'access-control-allow-origin': '*' }, json: [] }))
  await page.addInitScript(installEnginePortMock, THUMB)
}
